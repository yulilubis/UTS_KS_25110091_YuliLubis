    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        // 1. Validasi: Periksa apakah kode atau nama barang kosong
        if (txtKode.getText().trim().isEmpty() || txtNama.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Kode barang dan Nama barang tidak boleh kosong!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // 2. Validasi: Periksa apakah stok berupa angka dan bernilai >= 0
            int stok = Integer.parseInt(txtStok.getText().trim());
            if (stok < 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Stok harus berupa angka besar atau sama dengan 0!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 3. Ambil data dari form
            String kode = txtKode.getText().trim();
            String nama = txtNama.getText().trim();
            String kategori = cmbKategori.getSelectedItem().toString();

            // 4. Simpan ke database melalui class BarangDAO
            model.Barang brg = new model.Barang(kode, nama, kategori, stok);
            dao.BarangDAO dao = new dao.BarangDAO();
            
            boolean hasil = dao.tambahBarang(brg);
            if (hasil) {
                javax.swing.JOptionPane.showMessageDialog(this, "Data barang berhasil disimpan!");
                bersihkanForm();
                loadData(); // Memperbarui isi tabel secara otomatis
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan data barang.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Stok harus diisi dengan angka yang valid!", "Kesalahan Input", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnBersihkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBersihkanActionPerformed
        // TODO add your handling code here:
        bersihkanForm();
        }
    private void loadData() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblBarang.getModel();
        model.setRowCount(0); // Mengosongkan tabel

        try {
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/db_inventori", "root", "");
            java.sql.Statement stm = conn.createStatement();
            java.sql.ResultSet res = stm.executeQuery("SELECT * FROM barang");

            while (res.next()) {
                model.addRow(new Object[]{
                    res.getString("kode_barang"),
                    res.getString("nama_barang"),
                    res.getString("kategori"),
                    res.getInt("stok")
                });
            }
            res.close();
            stm.close();
            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }


    // Method tambahan untuk mengosongkan input form
    private void bersihkanForm() {
        txtKode.setText("");
        txtNama.setText("");
        cmbKategori.setSelectedIndex(0);
        txtStok.setText("");
        txtKode.requestFocus();
    }//GEN-LAST:event_btnBersihkanActionPerformed

    private void tblBarangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBarangMouseClicked
        // TODO add your handling code here:
        // Mengambil baris yang sedang diklik pada tabel
    int baris = tblBarang.getSelectedRow();
    if (baris != -1) {
        // Mengisi textfield dengan data dari baris yang diklik
        txtKode.setText(tblBarang.getValueAt(baris, 0).toString());
        txtNama.setText(tblBarang.getValueAt(baris, 1).toString());
        cmbKategori.setSelectedItem(tblBarang.getValueAt(baris, 2).toString());
        txtStok.setText(tblBarang.getValueAt(baris, 3).toString());
        
        // Kode barang tidak boleh diubah saat proses UBAH
        txtKode.setEditable(false); 
    }
    }//GEN-LAST:event_tblBarangMouseClicked

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        // 1. Cek apakah kolom kode masih kosong (artinya belum ada baris yang diklik/dipilih)
    if (txtKode.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Silakan klik/pilih data yang ingin dihapus terlebih dahulu dari tabel!");
        return;
    }

    // 2. Munculkan kotak konfirmasi sebelum menghapus
    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Apakah Anda yakin ingin menghapus data dengan kode: " + txtKode.getText() + "?", 
            "Konfirmasi Hapus", javax.swing.JOptionPane.YES_NO_OPTION);

    // 3. Jika pengguna menekan tombol "Yes"
    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
        String kode = txtKode.getText().trim();
        dao.BarangDAO dao = new dao.BarangDAO();
        
        // Memanggil method hapus dari BarangDAO
        boolean hasil = dao.hapusBarang(kode);
        if (hasil) {
            javax.swing.JOptionPane.showMessageDialog(this, "Data barang berhasil dihapus!");
            bersihkanForm();
            loadData(); // Memperbarui isi tabel secara otomatis
            txtKode.setEditable(true); // Mengaktifkan kembali kolom kode
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus data barang.");
        }
    }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        // 1. Cek apakah kode barang kosong (artinya belum ada data yang dipilih dari tabel)
    if (txtKode.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih data yang ingin diubah terlebih dahulu dari tabel!");
        return;
    }

    try {
        // 2. Ambil data dari form input
        String kode = txtKode.getText().trim();
        String nama = txtNama.getText().trim();
        String kategori = cmbKategori.getSelectedItem().toString();
        int stok = Integer.parseInt(txtStok.getText().trim());

        // 3. Kirim data ke BarangDAO untuk di-update ke database
        model.Barang brg = new model.Barang(kode, nama, kategori, stok);
        dao.BarangDAO dao = new dao.BarangDAO();
        
        boolean hasil = dao.ubahBarang(brg);
        if (hasil) {
            javax.swing.JOptionPane.showMessageDialog(this, "Data barang berhasil diubah!");
            bersihkanForm();
            loadData(); // Memperbarui tabel secara otomatis
            txtKode.setEditable(true); // Mengaktifkan kembali kolom kode jika dibersihkan
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah data barang.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Stok harus diisi dengan angka yang valid!", "Kesalahan Input", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnUbahActionPerformed

